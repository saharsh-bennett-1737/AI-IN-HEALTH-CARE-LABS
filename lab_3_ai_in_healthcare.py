def bandpass_filter(
    signal,
    lowcut,
    highcut,
    fs,
    order=4
):

    nyquist = 0.5 * fs

    low = (
        lowcut /
        nyquist
    )

    high = (
        highcut /
        nyquist
    )

    b, a = butter(
        order,
        [
            low,
            high
        ],
        btype="band"
    )

    filtered = filtfilt(
        b,
        a,
        signal
    )

    return filtered


