def extract_ecg_features(window):

    return {

        "mean":
            np.mean(window),

        "std":
            np.std(window),

        "min":
            np.min(window),

        "max":
            np.max(window),

        "median":
            np.median(window),

        "range":
            np.max(window)
            -
            np.min(window),

        "energy":
            np.sum(
                window ** 2
            )
    }


